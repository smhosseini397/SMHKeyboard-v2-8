#!/usr/bin/env python3
"""Offline integrity checks for KeyFarsi source and bundled learning resources."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
checks = [
    ROOT / "KeyFarsi-Learning/learning_profile_template.json",
    ROOT / "KeyFarsi-Learning/learning_profile.schema.json",
    ROOT / "KeyFarsi-Learning/seed_corrections.json",
    ROOT / "app/src/main/assets/learning/learning_profile_template.json",
    ROOT / "app/src/main/assets/learning/learning_profile.schema.json",
    ROOT / "app/src/main/assets/learning/seed_corrections.json",
    ROOT / "app/src/main/assets/fa_words.txt",
    ROOT / "app/src/main/assets/semantic/model_manifest.json",
]
for path in checks:
    assert path.is_file() and path.stat().st_size > 0, f"Missing/empty: {path.relative_to(ROOT)}"

for rel in [
    "KeyFarsi-Learning/learning_profile_template.json",
    "KeyFarsi-Learning/learning_profile.schema.json",
    "KeyFarsi-Learning/seed_corrections.json",
]:
    json.loads((ROOT / rel).read_text(encoding="utf-8"))

for name in ["learning_profile_template.json", "learning_profile.schema.json", "seed_corrections.json"]:
    assert (ROOT / "KeyFarsi-Learning" / name).read_bytes() == (ROOT / "app/src/main/assets/learning" / name).read_bytes(), f"Out of sync: {name}"

manifest = json.loads((ROOT / "app/src/main/assets/semantic/model_manifest.json").read_text(encoding="utf-8"))
assert manifest["model_id"] == "shekar-ai/albert-base-v2-persian-zwnj-naab-mlm"
assert set(manifest["required_runtime_assets"]) == {"albert_persian_mlm.onnx", "spiece.model", "special_tokens.json"}
print(f"OK: {len(checks)} required files present; JSON valid; mirrored learning assets synchronized.")
print("NOTE: model binaries are generated by scripts/export_persian_albert_onnx.py and must exist before a model-enabled APK is built.")
